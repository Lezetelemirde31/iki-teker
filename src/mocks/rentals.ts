export const bookingById = new Map(bookings.map((booking) => [booking.id, booking]));

export function bookingsForOwner(ownerId: string) {
  return bookings.filter((booking) => booking.ownerId === ownerId);
}

export function bookingsForRenter(renterId: string) {
  return bookings.filter((booking) => booking.renterId === renterId);
}

/** Requests still waiting on the owner — the dashboard's "N new" badge. */
export function pendingRequestsForOwner(ownerId: string) {
  return bookings.filter((booking) => booking.ownerId === ownerId && booking.status === "pending");
}

/** Completed rental revenue for an owner within a month, e.g. "2026-07". */
export function monthlyIncome(ownerId: string, month: string) {
  return bookings
    .filter(
      (booking) =>
        booking.ownerId === ownerId &&
        booking.status === "returned" &&
        booking.start.startsWith(month),
    )
    .reduce((total, booking) => total + booking.subtotal, 0);
}
