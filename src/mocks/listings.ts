/**
 * Listing artwork is generated, not photographic: a tinted gradient plate with a
 * vehicle silhouette, exactly as in the source prototype. Nothing to fetch, so
 * a demo can run offline and no image ever fails to load.
 */
function makePhotos(seed: string, count: number, tone: ArtTone, alt: string): Photo[] {
  return Array.from({ length: count }, (_, index) => ({
    id: `${seed}-p${index + 1}`,
    seed: `${seed}-${index + 1}`,
    tone,
    alt: `${alt} — ${index + 1}`,
  }));
}

const slugify = (value: string) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

type VehicleSeed = {
  id: string;
  category: VehicleCategorySlug;
  make: string;
  model: string;
  year: number;
  price: number;
  negotiable?: boolean;
  condition?: Condition;
  customsCleared?: boolean;
  delivery?: boolean;
  sellerId: string;
  cityId: string;
  districtId: string;
  tone: ArtTone;
  photoCount: number;
  attributes: AttributeValues;
  description: LocalizedText;
  publishedAt: string;
  views: number;
  contacts: number;
  favorites: number;
  vip?: boolean;
  vipUntil?: ISODate;
  bumpsLeft?: number;
  lastBumpedAt?: string;
  status?: ListingStatus;
  rentalOfferId?: string;
};

function build(seed: VehicleSeed): Listing {
  const title = `${seed.make} ${seed.model}, ${seed.year}`;
  return {
    kind: "vehicle",
    id: seed.id,
    slug: `${slugify(`${seed.make}-${seed.model}-${seed.year}`)}-${seed.id.slice(-4)}`,
    title,
    category: seed.category,
    makeId: `make-${slugify(seed.make)}`,
    modelId: `model-${slugify(seed.make)}-${slugify(seed.model)}`,
    makeName: seed.make,
    modelName: seed.model,
    year: seed.year,
    price: seed.price,
    negotiable: seed.negotiable ?? false,
    condition: seed.condition ?? "used",
    customsCleared: seed.customsCleared ?? true,
    delivery: seed.delivery ?? false,
    description: seed.description,
    photos: makePhotos(seed.id, seed.photoCount, seed.tone, title),
    attributes: seed.attributes,
    sellerId: seed.sellerId,
    cityId: seed.cityId,
    districtId: seed.districtId,
    status: seed.status ?? "active",
    promotion: {
      vip: seed.vip ?? false,
      vipUntil: seed.vipUntil,
      bumpsLeft: seed.bumpsLeft,
      lastBumpedAt: seed.lastBumpedAt,
    },
    stats: { views: seed.views, contacts: seed.contacts, favorites: seed.favorites },
    publishedAt: seed.publishedAt,
    rentalOfferId: seed.rentalOfferId,
  };
}

